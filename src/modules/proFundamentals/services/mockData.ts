// Helper to generate 30 days of realistic history leading up to the current scores
function generateHistory(baseShort: number, baseLong: number): { date: string; short: number; long: number }[] {
  const history: { date: string; short: number; long: number }[] = [];
  const now = new Date('2026-10-15T00:00:00Z');

  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    // Natural macroeconomic mean-reverting drift
    const shortVariance = Math.round(Math.sin(i * 0.4) * 6 + ((29 - i) / 29) * 4);
    const longVariance = Math.round(Math.cos(i * 0.3) * 3);
    const s = Math.max(-100, Math.min(100, baseShort - shortVariance));
    const l = Math.max(-100, Math.min(100, baseLong - longVariance));
    history.push({ date: dateStr, short: s, long: l });
  }
  return history;
}

