// Two separate servers (own disks) sharing only the encrypted account store.
const A = 'http://localhost:3000', B = 'http://localhost:3001';
const j = async (base, path, opt = {}) => { const r = await fetch(base + path, { ...opt, headers: { 'Content-Type': 'application/json', ...(opt.headers || {}) }, body: opt.body ? JSON.stringify(opt.body) : undefined }); let d = null; try { d = await r.json(); } catch {} return { s: r.status, d }; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const u = 'citest' + Date.now().toString(36);
let r = await j(A, '/api/auth/register', { method: 'POST', body: { username: u, password: 'first-pass-1', name: 'CI Test' } });
console.log('ACCT register on A', r.s, r.d?.ok, r.d?.error || '');
await sleep(5000);
r = await j(B, '/api/auth/login', { method: 'POST', body: { username: u, password: 'first-pass-1' } });
console.log('ACCT login on B (other server)', r.s, r.d?.ok);
const adm = await j(A, '/api/auth/login', { method: 'POST', body: { username: 'primepipfx-admin', password: process.env.PRIMEPIPFX_BOOTSTRAP_ADMIN_PASSWORD } });
const H = { Authorization: 'Bearer ' + adm.d?.token };
console.log('ACCT admin login', adm.s, adm.d?.ok);
let list = await j(A, '/api/admin/customers', { headers: H });
const me = list.d?.customers?.find((c) => c.username === u);
console.log('ACCT customers on A', list.d?.customers?.length, 'found new', Boolean(me));
r = await j(A, `/api/admin/customers/${me?.id}/reset-password`, { method: 'POST', headers: H, body: {} });
console.log('ACCT reset password on A', r.s, r.d?.ok, r.d?.error || '', 'new password issued', Boolean(r.d?.password));
const np = r.d?.password;
await sleep(5000);
r = await j(B, '/api/auth/login', { method: 'POST', body: { username: u, password: np } });
console.log('ACCT login on B with NEW password', r.s, r.d?.ok);
r = await j(B, '/api/auth/login', { method: 'POST', body: { username: u, password: 'first-pass-1' } });
console.log('ACCT login on B with OLD password (must fail)', r.s, r.d?.ok);
r = await j(B, `/api/admin/customers/${me?.id}`, { method: 'PUT', headers: H, body: { subscriptionStatus: 'LIFETIME', isLifetime: true, name: 'CI Edited' } });
console.log('ACCT edit on B', r.s, r.d?.ok, r.d?.error || '');
await sleep(5000);
list = await j(A, '/api/admin/customers', { headers: H });
const e = list.d?.customers?.find((c) => c.username === u);
console.log('ACCT edit seen on A', e?.name, e?.subscriptionStatus);
r = await j(A, '/api/admin/customers', { method: 'POST', headers: H, body: { name: 'CI Created', username: u + 'x', subscriptionStatus: 'ACTIVE', paymentStatus: 'VERIFIED', subscriptionPrice: 50 } });
console.log('ACCT create customer on A', r.s, r.d?.ok, r.d?.error || '', Boolean(r.d?.generatedPassword));
await sleep(5000);
const r2 = await j(B, '/api/auth/login', { method: 'POST', body: { username: u + 'x', password: r.d?.generatedPassword } });
console.log('ACCT created customer logs in on B', r2.s, r2.d?.ok);
r = await j(A, `/api/admin/customers/${me?.id}`, { method: 'DELETE', headers: H });
console.log('ACCT delete on A', r.s, r.d?.ok);
await sleep(5000);
list = await j(B, '/api/admin/customers', { headers: H });
console.log('ACCT deleted gone on B', !list.d?.customers?.some((c) => c.username === u), 'total', list.d?.customers?.length);
const mem = await j(B, '/api/admin/members', { headers: H });
console.log('ACCT storage', JSON.stringify(mem.d?.storage));
const dg = await j(A, '/api/macro/diagnostics');
for (const s of (Array.isArray(dg.d?.sources) ? dg.d.sources : Object.entries(dg.d?.sources || {}).map(([k, v]) => ({ id: k, ...v })))) console.log('SRC', (s.id || s.name || '').toString().padEnd(22), s.ok === false || s.status === 'error' ? 'FAIL' : 'ok', (s.status || ''), s.updatedAt || s.fetchedAt || s.asOf || '', (s.error || '').toString().slice(0, 80), s.count ?? s.items ?? '');
console.log('SRC unmatched calendar titles', (dg.d?.unmatchedCalendarTitles || []).length);
